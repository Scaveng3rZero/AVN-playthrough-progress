/* ===== Helpers ===== */

function getSteamAppId(url) {
  var match = url && url.match(/\/app\/(\d+)\//i);
  return match ? match[1] : null;
}


function getDefaultImage() {
  return "img/default.jpg";
}


/*
 * Finds the Steam URL regardless of whether
 * the game uses the OLD or NEW data format.
 */
function getSteamUrl(item) {

  if (!item) return null;


  /*
   * NEW FORMAT
   *
   * links: {
   *   steam: "..."
   * }
   */
  if (
    item.links &&
    typeof item.links === "object" &&
    item.links.steam
  ) {
    return item.links.steam;
  }


  /*
   * OLD FORMAT
   *
   * platform: "steam",
   * url: "..."
   */
  if (
    item.platform === "steam" &&
    item.url
  ) {
    return item.url;
  }


  return null;
}


function getAutoImage(item) {

  if (!item) {
    return getDefaultImage();
  }


  /*
   * First use one of our manually supplied
   * images if the game has one.
   */
  if (GAME_IMAGE_OVERRIDES[item.title]) {
    return GAME_IMAGE_OVERRIDES[item.title];
  }


  /*
   * Otherwise automatically grab the
   * Steam header when a Steam URL exists.
   */
  var steamUrl =
    getSteamUrl(item);


  if (steamUrl) {

    var appId =
      getSteamAppId(steamUrl);


    if (appId) {

      return (
        "https://cdn.cloudflare.steamstatic.com/" +
        "steam/apps/" +
        appId +
        "/header.jpg"
      );

    }

  }


  return getDefaultImage();
}


/*
 * Cleans arrays such as:
 *
 * tags: ["rpg", "horror"]
 *
 * or:
 *
 * tags: ["rpg, horror"]
 */
function normalizeArray(items) {

  if (!Array.isArray(items)) {
    return [];
  }


  return items
    .flatMap(function (item) {

      return String(item)
        .split(",");

    })

    .map(function (item) {

      return item.trim();

    })

    .filter(Boolean);

}


/*
 * Clean the new links object.
 *
 * links: {
 *   steam: "...",
 *   itch: "...",
 *   patreon: "..."
 * }
 */
function normalizeLinks(links) {

  var cleaned = {};


  if (
    !links ||
    typeof links !== "object"
  ) {
    return cleaned;
  }


  Object.keys(links)
    .forEach(function (platform) {

      var url = links[platform];


      if (
        typeof url === "string" &&
        url.trim()
      ) {

        cleaned[platform] =
          url.trim();

      }

    });


  return cleaned;
}


